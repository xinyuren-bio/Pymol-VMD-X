def _lookup(body: str) -> Optional[str]:
    """把一段不含颜色码的英文译成中文。译不了就返回空。"""
    if body in PHRASE:
        return PHRASE[body]
    m = _SECOND_PAUSE.fullmatch(body)
    if m:
        return "停顿 %s 秒" % m.group(1)
    m = _SECOND_EACH.fullmatch(body)
    if m:
        return "每个 %s 秒" % m.group(1)
    m = _SECOND.fullmatch(body)
    if m:
        return "%s 秒" % m.group(1)
    m = _DEG_OVER.fullmatch(body)
    if m:
        return "%s 度，用 %s 秒" % (m.group(1), m.group(2))
    m = _ANG_SPHERE.fullmatch(body)
    if m:
        return "%s 埃范围" % m.group(1)
    m = _ANG_SLAB.fullmatch(body)
    if m:
        return "%s 埃厚的切片" % m.group(1)
    m = _N_POINT.fullmatch(body)
    if m:
        return "%s 点" % m.group(1)
    m = _N_ANG.fullmatch(body)
    if m:
        return "%s 埃" % m.group(1)
    m = _N_CYCLES.fullmatch(body)
    if m:
        return "每次更新 %s 轮" % m.group(1)
    m = _N_FPS.fullmatch(body)
    if m:
        return "%s 帧/秒" % m.group(1)
    m = _N_SOLV.fullmatch(body)
    if m:
        return "%s 个溶剂半径" % m.group(1)
    m = _SPEED.fullmatch(body)
    if m:
        return "1/%s 速度" % m.group(1)
    m = _SETN.fullmatch(body)
    if m:
        return "第 %s 套" % m.group(1)
    m = _WITHIN_A.fullmatch(body)
    if m:
        return "%s 埃以内" % m.group(1)
    m = _BY_A_RES.fullmatch(body)
    if m:
        return "向外 %s 埃（按残基）" % m.group(1)
    m = _BY_A.fullmatch(body)
    if m:
        return "向外 %s 埃" % m.group(1)
    m = _ATOMS_WITHIN.fullmatch(body)
    if m:
        return "%s 埃内的原子" % m.group(1)
    m = _RES_WITHIN.fullmatch(body)
    if m:
        return "%s 埃内的残基" % m.group(1)
    m = _BY_BOND_RES.fullmatch(body)
    if m:
        return "延伸 %s 根键（按残基）" % m.group(1)
    m = _BY_BOND.fullmatch(body)
    if m:
        return "延伸 %s 根键" % m.group(1)
    m = _LEVEL.fullmatch(body)
    if m:
        return "等值 %s" % m.group(1)
    if body.startswith("Scene ") and body != "Scene:":
        return "场景 " + body[6:]
    parts = body.split(" ")
    out = []
    for p in parts:
        if not p:
            continue
        if p in PHRASE:
            out.append(PHRASE[p])
        elif p.lower() in WORD:
            out.append(WORD[p.lower()])
        else:
            return None
    if not out:
        return None
    return "".join(out)


def _plain(text: str) -> str:
    """翻译一段普通文字，并保留原来的前后空格和快捷键。"""
    if not text:
        return text
    lead = len(text) - len(text.lstrip(" "))
    core = text.strip(" ")
    trail_n = len(text) - len(text.rstrip(" "))
    if not core:
        return text
    suffix = ""
    body = core
    m = _SHORTCUT.fullmatch(core)
    if m:
        body, suffix = m.group(1), m.group(2)
    hit = _lookup(body)
    if hit is None:
        return text
    return (" " * lead) + hit + suffix + (" " * trail_n)


def zh(s: str) -> str:
    """把界面标签译成中文。颜色码和译不了的原文会原样留下。"""
    if not isinstance(s, str) or not s:
        return s
    parts = _COLOR.split(s)
    codes = _COLOR.findall(s)
    out = []
    for i, part in enumerate(parts):
        out.append(_plain(part))
        if i < len(codes):
            out.append(codes[i])
    return "".join(out)


def translate_menu(obj: Any) -> Any:
    """只替换菜单项里给人看的标题，命令字符串不动。"""
    if isinstance(obj, list):
        if (
            len(obj) >= 2
            and isinstance(obj[0], int)
            and isinstance(obj[1], str)
        ):
            nxt = list(obj)
            nxt[1] = zh(obj[1])
            for i in range(2, len(nxt)):
                if isinstance(nxt[i], list):
                    nxt[i] = translate_menu(nxt[i])
            return nxt
        return [translate_menu(x) for x in obj]
    return obj
