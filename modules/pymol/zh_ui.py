_N_ANG = re.compile(r"^(\d+(?:\.\d+)?) Angstrom$")
_N_CYCLES = re.compile(r"^(\d+) Cycles per Update$")
_N_FPS = re.compile(r"^(\d+(?:\.\d+)?) FPS$")
